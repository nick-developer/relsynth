"""Oracle Database (python-oracledb, thin mode): LOBs fetched as values, array
binding for loads, identity columns restarted after the loaded keys.

Oracle stores an empty string as NULL; text columns whose source has empty
strings therefore read back as nulls."""
from __future__ import annotations


from .sql import SqlConnector


class OracleConnector(SqlConnector):
    kind = "oracle"

    def _engine_options(self, url):
        return {"arraysize": 10_000}

    def _setup_engine(self, engine):
        try:
            import oracledb
            oracledb.defaults.fetch_lobs = False       # CLOB/BLOB as str/bytes, not LOB handles
        except ImportError:
            pass

    def after_load(self, con, tbl):
        prep = con.dialect.identifier_preparer
        for c in tbl.columns:
            if c.identity is None:
                continue
            con.exec_driver_sql(f"ALTER TABLE {prep.format_table(tbl)} MODIFY ({prep.format_column(c)} "
                                "GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))")
